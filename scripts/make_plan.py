def _cn(run, name, size, bold=False, color=None):
    run.font.name = name
    r = run._element.rPr.rFonts
    r.set(qn("w:eastAsia"), name)
    run.font.size = Pt(size)
    run.font.bold = bold
    if color is not None:
        run.font.color.rgb = color


def para(text, size=12, bold=False, align=None, name="宋体", color=None,
         space_before=0, space_after=6, indent=True):
    p = doc.add_paragraph()
    if align is not None:
        p.alignment = align
    pf = p.paragraph_format
    pf.space_before = Pt(space_before)
    pf.space_after = Pt(space_after)
    pf.line_spacing = 1.35
    if indent and align != WD_ALIGN_PARAGRAPH.CENTER:
        pf.first_line_indent = Pt(24)
    r = p.add_run(text)
    _cn(r, name, size, bold, color)
    return p


