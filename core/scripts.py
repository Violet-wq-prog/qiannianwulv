# ———— 故地重游·站点问答：关键词分支模板 ————
_KW_WHY = ["为什么", "为何", "原因", "缘由"]
_KW_FEEL = ["心情", "感受", "想法", "难过", "苦", "后悔", "怕", "想家"]
_KW_LATER = ["后来", "然后", "之后", "接着", "以后"]
_KW_FOOD = ["吃", "美食", "酒", "茶", "菜"]
_KW_WORK = ["诗", "词", "文章", "作品", "写", "画", "发明", "造"]
_KW_FRIEND = ["朋友", "家人", "妻子", "丈夫", "爱", "知己"]


def offline_site_reply(person: dict, entry: dict, user_input: str) -> str:
    """站点对话降级应答：优先命中关键词分支，否则以故事要点+引导收尾。"""
    kw = user_input.strip()
    name = person["name"]
    voice = person["personality"]
    story, note, opener = entry.get("story", ""), entry.get("note", ""), entry.get("opener", "")
    hobbies = "、".join(person["hobbies"][:2])

    if any(k in kw for k in _KW_WHY):
        return (f"说起缘故，我{note}。{story} 如今回头看，是非对错已不重要，"
                f"要紧的是那时我心里清清楚楚——该做的，便去做了。")
    if any(k in kw for k in _KW_FEEL):
        return (f"你问我当时什么心境？——{voice}，这四字便是我的性子。{story}"
                f" 苦是苦的，可人这一生，总要把苦嚼出点滋味来。")
    if any(k in kw for k in _KW_LATER):
        return (f"后来啊……{story} 再往后，我{'; '.join(person['achievements'][:2])}。"
                f"这一路走下来，才明白山水与人，皆是缘分。")
    if any(k in kw for k in _KW_FOOD):
        if "美食" in person["hobbies"] or any("吃" in h or "酒" in h or "茶" in h for h in person["hobbies"]):
            return (f"哈哈，你倒问到我的心头好了。我平生好{hobbies}。{story}"
                    f" 这儿的滋味，你要亲口尝过，才算真正来过。")
        return (f"吃食上我不算讲究，却也懂得：{hobbies}最养人心。{story}")
    if any(k in kw for k in _KW_WORK):
        return (f"要论这{person['category']}的本事——{'; '.join(person['achievements'][:2])}。"
                f"{story} 旁人问我诀窍，无非'用心'二字罢了。")
    if any(k in kw for k in _KW_FRIEND):
        return (f"至亲至近之人，是我的软肋，也是我的铠甲。{story}"
                f" 如今想起他们，心里仍是暖的。")
    # 默认：重申此站往事 + 引导继续
    return (f"{story} 你还有什么想问的？问我当年的心境、缘由，或是这儿的吃食旧俗，"
            f"我都愿意说给你听。")


def offline_poem(person: dict, user_name: str) -> str:
    """离线藏头诗降级：以名句旧句相赠（落款人物）。"""
    name = user_name.strip() or "游客"
    return (f"《赠{name}》\n（离线演示：暂以旧句相赠）\n"
            f"{person['quote']}\n——{person['name']} 赠")


# ———— 单人对话降级应答 ————
def offline_solo_reply(person: dict, user_input: str) -> str:
    kw = user_input.strip()
    name = person["name"]
    if not kw or any(k in kw for k in ["你好", "您好", "你是谁", "自我介绍", "介绍一下"]):
        return person["self_talk"]
    if any(k in kw for k in ["爱好", "喜欢", "兴趣", "平时"]):
        return (f"我平生所好：{'、'.join(person['hobbies'])}。"
                f"「{person['quote']}」——这话，道尽我的性子。")
    if any(k in kw for k in ["成就", "事迹", "发明", "作品", "代表作", "厉害"]):
        return (f"若说这一生做过什么——{'；'.join(person['achievements'][:3])}。"
                f"这些都不是为了虚名，只是时势推着人往前走，我便把它走稳了。")
    if any(k in kw for k in ["现代", "手机", "电脑", "网络", "高铁", "飞机", "汽车", "电视"]):
        return (f"你说的这物事，于我如天外仙器一般。我那时候，传一封信要走上月余。"
                f"不过我想，人心里的情义，大约千年也变不了多少。")
    if any(k in kw for k in ["难过", "苦", "难", "后悔", "遗憾"]):
        return (f"谁没有几段难捱的日子呢。我是{person['personality']}的性子，"
                f"再难，也记得「{person['quote']}」。你若有烦心事，不妨也说与我听听。")
    if any(k in kw for k in ["诗", "词", "文章", "写"]):
        return (f"写诗作文，贵在真情。我那时{person['achievements'][0]}，"
                f"不过把心里话交给笔墨。你若有兴，我讲几段创作时的旧事与你听。")
    first = person["places"][0] if person.get("places") else None
    if any(k in kw for k in ["去过", "游历", "旅行", "地方", "故地"]):
        if first:
            return (f"我行过不少地方。印象最深的，要数{_place_display(first)}——{first['note']}。"
                    f"这些山水城池，后来都成了我文章里的故乡。")
        return "我行过的地方不少，可惜笔墨有限，未能一一记下。"
    # 兜底
    return (f"这桩事，说来话长。{person['self_talk']} "
            f"你可以问我的生平经历、心头所好，或是我那几桩传世的事迹。")


def _place_display(entry: dict) -> str:
    return entry.get("place_name") or entry["place_id"]


