# 剧本覆盖之外的人物兜底台词模板
def generic_line_for(person: dict, idx: int) -> str:
    lines = GENERIC_GROUP_LINES.get(person["id"])
    if lines:
        return lines[idx % len(lines)]
    return (f"（{person['name']}闻言一笑）我{person['dynasty']}人说话直——"
            f"「{person['quote']}」。诸君高论，我也凑一句：且把心放宽些。")


def offline_group_turn(members: list[dict], history: list[dict],
                       user_input: str, turn_no: int) -> list[dict]:
    """群聊降级：命中预置剧本按序推进；否则每人输出通用台词。

    turn_no：本轮到场人物已发言的总句数（不含游客消息），驱动剧本与台词轮换。
    返回本轮新增的消息列表 [{"speaker","content"}]。
    """
    key = tuple(sorted(m["id"] for m in members))
    play = GROUP_PLAYS.get(key)
    if play:
        # 剧本模式：开场取首句，此后游客每发言一次推进一句，直到剧本末尾
        line = play[min(turn_no, len(play) - 1)]
        return [{"speaker": line[0], "content": line[1]}]
    # 通用模式：每位在场人物各回一句（按各自台词循环）
    return [
        {"speaker": m["name"], "content": generic_line_for(m, turn_no + i)}
        for i, m in enumerate(members)
    ]
